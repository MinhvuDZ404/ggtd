let LANG = 'vi';
export function setLang(l) { LANG = l; bus.emit('lang', l); document.querySelectorAll('[data-i18n]').forEach(n => { n.textContent = t(n.dataset.i18n); }); }
export function getLang() { return LANG; }
export function t(key, vars) {
  let s = DICT[LANG]?.[key] ?? DICT.vi[key] ?? DICT.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll('{' + k + '}', vars[k]);
  return s;
}
export function tData(obj, field) {
  if (!obj) return '';
  const v = obj[field];
  if (!v) return '';
  if (typeof v === 'string') return v;
  return v[LANG] ?? v.vi ?? v.en ?? '';
}
